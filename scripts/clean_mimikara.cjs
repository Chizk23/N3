for (let stt = 1; stt <= 880; stt++) {
  const rawItem = raw.find(r => r.stt === stt) || {};
  let kanji = rawItem.kanji || '';
  let reading = rawItem.reading || '';
  let hanViet = rawItem.hanViet || '';
  let meaning = rawItem.meaning || '';

  // Apply overrides if any
  if (OVERRIDES[stt]) {
    const ov = OVERRIDES[stt];
    if (ov.kanji !== undefined) kanji = ov.kanji;
    if (ov.reading !== undefined) reading = ov.reading;
    if (ov.meaning !== undefined) meaning = ov.meaning;
    if (ov.hanViet !== undefined) hanViet = ov.hanViet;
  }

  // Set canonical Han Viet
  if (CANONICAL_HAN_VIET[stt]) {
    hanViet = CANONICAL_HAN_VIET[stt];
  } else if (!kanji || !/[\u4E00-\u9FFF]/.test(kanji)) {
    hanViet = '';
  }

  // Clean Vietnamese meaning
  meaning = fixVietnameseText(meaning);

  // If reading is empty and kanji is kana, set reading
  if (!reading && kanji && /^[\u3040-\u309F\u30A0-\u30FF]+$/.test(kanji)) {
    reading = kanji;
  }
  if (!kanji && reading) {
    // kana word
    kanji = '';
  }

  // Display word
  const displayWord = kanji || reading;

  finalItems.push({
    id: `MIMIKARA-${String(stt).padStart(4, '0')}`,
    stt,
    kanji,
    hanViet,
    reading,
    meaning,
    displayWord
  });
}

